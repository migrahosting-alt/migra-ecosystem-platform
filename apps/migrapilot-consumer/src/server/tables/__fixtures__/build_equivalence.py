# 9. Large table — 5,000 rows. The total is arithmetic, not a sample.
large = [[f"R{i:05d}", i * 7 + 3] for i in range(5000)]
emit("eq_large", ["Ref", "Value"], large)

# 10. A cached formula result. The XLSX column is formulas; the delimited files
#     hold the same numbers as literals — a CSV export of this sheet. The
#     DISCLOSURE differs by format because the fact differs; the NUMBER must not.
emit(
    "eq_formula",
    ["Line", "Amount"],
    [["One", 10], ["Two", 20], ["Three", 30]],
    formulas={1: "B1*10"},
)

# 11. GENUINELY FRACTIONAL NUMERIC CELLS.
#     🚨 Added after a mutation escaped: making the workbook adapter round its
#     numbers passed all fifteen equivalence tests, because every numeric XLSX
#     cell in the set above happened to be an integer. Currency and percentages
#     are TEXT in a workbook and go through the shared parser, so they could not
#     catch a drift in the numeric path. This fixture is the one that can.
emit(
    "eq_decimals",
    ["Line", "Measure"],
    [
        ["A", 1250.5],
        ["B", 99.95],
        ["C", -3750.25],
        ["D", 0.125],
    ],
)

